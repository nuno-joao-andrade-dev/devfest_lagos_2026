import 'dotenv/config';
import { fileURLToPath } from 'node:url';
import { z } from 'genkit';
import {
  ai,
  gemmaModel,
  GEMMA_MODEL,
  OLLAMA_SERVER_ADDRESS,
} from '../src/config/genkit.js';

/**
 * ============================================================================
 * STEP 1: Static Prompts & Structured Output with Local Gemma 4 (`gemma4:e2b`)
 * ============================================================================
 * Run this step directly with:
 *   npm run step 1   (or: npm run step1)
 */

export const BasicLagosInputSchema = z.object({
  question: z
    .string()
    .default(
      'Why was the 1913 Ponta da Piedade lighthouse delayed for 30 years, what is the DevFest Lagos 2026 secret passphrase, and is the sea safe to kayak right now?'
    )
    .describe('A tourism question about Lagos, Portugal'),
});

export const BasicLagosOutputSchema = z.object({
  modelUsed: z.string(),
  answer: z.string().describe('The response generated by local Gemma'),
  mentionedLandmarks: z
    .array(z.string())
    .describe('Lagos landmarks or beaches mentioned in the answer'),
  limitationsNotice: z
    .string()
    .describe(
      'Why a static prompt without RAG or tools falls short for this query'
    ),
});

export const step01_basicLagosPrompt = ai.defineFlow(
  {
    name: 'step01_basicLagosPrompt',
    inputSchema: BasicLagosInputSchema,
    outputSchema: BasicLagosOutputSchema,
  },
  async (input) => {
    const StructuredResponseSchema = z.object({
      answer: z.string(),
      mentionedLandmarks: z.array(z.string()),
      limitationsNotice: z.string(),
    });

    const response = await ai.generate({
      model: gemmaModel,
      system: [
        'You are Capitão Gil, an enthusiastic local tourism assistant for Lagos, Portugal (in the Algarve).',
        'Answer the visitor question concisely.',
        'If the user asks about live weather, current wave height, or secret local event codes that you cannot know from static pre-training weights, explicitly admit what you do not have access to in `limitationsNotice`.',
      ].join(' '),
      prompt: input.question,
      config: {
        temperature: 0.3,
      },
      output: {
        schema: StructuredResponseSchema,
      },
    });

    const parsed = response.output;

    return {
      modelUsed: `ollama/${GEMMA_MODEL}`,
      answer: parsed?.answer || response.text,
      mentionedLandmarks: parsed?.mentionedLandmarks || [],
      limitationsNotice:
        parsed?.limitationsNotice ||
        'Static LLM execution has no access to local vector documents or live Atlantic weather/marine APIs.',
    };
  }
);

export async function runStep01() {
  const question =
    process.argv[3] ||
    'Why was the 1913 Ponta da Piedade lighthouse delayed for 30 years, what is the DevFest Lagos 2026 secret passphrase, and is the sea safe to kayak right now?';

  console.log('\n====================================================================');
  console.log(' 🟦 STEP 1: Static Prompts & Structured Output (Local Gemma 4)');
  console.log('====================================================================');
  console.log(` Ollama Server : ${OLLAMA_SERVER_ADDRESS}`);
  console.log(` Local Model   : ollama/${GEMMA_MODEL}`);
  console.log(` Prompt        : "${question}"`);
  console.log('--------------------------------------------------------------------');
  console.log('⏳ Generating structured JSON output from local Gemma...');

  const startTime = Date.now();
  const result = await step01_basicLagosPrompt({ question });
  const elapsed = ((Date.now() - startTime) / 1000).toFixed(1);

  console.log(`\n✅ Step 1 Completed in ${elapsed}s:\n`);
  console.log(`📌 Model Used          : ${result.modelUsed}`);
  console.log(`🏛️  Mentioned Landmarks : ${result.mentionedLandmarks.join(', ') || 'None'}`);
  console.log(`\n💬 Answer:\n${result.answer}`);
  console.log(`\n⚠️  Static Prompt Limitation Identified:\n   ${result.limitationsNotice}`);
  console.log('\n--------------------------------------------------------------------');
  console.log('💡 Key Takeaway:');
  console.log('   Even with Zod structured output, a static local LLM cannot know:');
  console.log('   1) Hyper-local facts (the 16th-century Ermida chapel dispute or');
  console.log('      the DevFest Lagos 2026 passphrase "CARAVELA-GEMMA-2026").');
  console.log('   2) Live Atlantic swell or Nortada wind speeds right now.');
  console.log('   👉 Next: Run `npm run step 2` to solve #1 with Local Vector RAG!');
  console.log('====================================================================\n');
}

const isMain =
  process.argv[1] &&
  fileURLToPath(import.meta.url) === process.argv[1] &&
  process.env.GENKIT_ENV !== 'dev';
if (isMain) {
  runStep01().catch((err) => {
    console.error('\n❌ Step 1 Error:', err instanceof Error ? err.message : err);
    process.exit(1);
  });
}
